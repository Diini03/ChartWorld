// ---- helpers to keep the file compact ---------------------------------------

const now = new Date("2026-07-15T09:00:00Z").getTime();
const iso = (offsetMinutes: number) => new Date(now - offsetMinutes * 60_000).toISOString();

const cols = (specs: string[]): Column[] =>
  specs.map((s) => {
    // "id:uuid!pk", "email:string?", "amount:numeric"
    const [head, type] = s.split(":");
    const nullable = type?.endsWith("?");
    const pk = head.endsWith("!pk");
    const fk = head.endsWith("!fk");
    const name = head.replace(/!pk|!fk/g, "");
    const cleanType = (type ?? "string").replace("?", "");
    return {
      name,
      type: cleanType,
      nullable: Boolean(nullable),
      isPrimary: pk,
      isForeign: fk,
    };
  });

const history90 = (base: number, variance = 8): QualityPoint[] =>
  Array.from({ length: 90 }, (_, i) => {
    const day = new Date(now - (89 - i) * 24 * 60 * 60_000);
    const noise = Math.sin(i / 4) * variance + (Math.random() - 0.5) * 4;
    const score = Math.max(30, Math.min(100, Math.round(base + noise)));
    return { date: day.toISOString().slice(0, 10), score };
  });

const checkSet = (status: "ok" | "warn" | "fail"): QualityCheck[] => [
  { key: "freshness", label: "Freshness", status: status === "fail" ? "fail" : "ok", detail: "Updated 14 min ago" },
  { key: "missing", label: "Missing values", status: status === "ok" ? "ok" : "warn", detail: "0.4% of order_id null" },
  { key: "schema_drift", label: "Schema drift", status: "ok", detail: "No changes in 7 days" },
  { key: "duplicates", label: "Duplicates", status: status === "fail" ? "fail" : "ok", detail: status === "fail" ? "312 duplicate ids" : "None detected" },
  { key: "row_delta", label: "Row count delta", status: "ok", detail: "+0.8% vs 24h avg" },
];

const version = (id: string, mins: number, author: string, summary: string, add: string[] = [], rem: string[] = []): Version => ({
  id,
  createdAt: iso(mins),
  author,
  summary,
  added: add,
  removed: rem,
  typeChanged: [],
});

